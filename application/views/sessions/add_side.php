<div class="bd-callout bd-callout-info">

	<dt>Ano letivo</dt>
	<dd>Defina aqui as datas de início e término do ano letivo.</dd>

	<dt>Formato da data</dt>
	<dd>Use o formato <span>DD/MM/YYYY</span> ao inserir datas. Por esemplo <em>16/04/2018</em>.</dd>

	<dt>Alterando datas</dt>
	<dd>Se você alterar a data de início ou término após os agendamentos terem sido feitos durante o ano letivo, os agendamentos existentes <em>fora do novo intervalo de datas</em> serão excluídos.</dd>
